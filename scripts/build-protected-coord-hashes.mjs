#!/usr/bin/env node
/**
 * Regenerates scripts/protected-coords.hashes.json: keyed HMAC-SHA256 hashes of every known exact
 * (≥2-decimal) coordinate pair for the protected (looting-sensitive) sites, taken from git history:
 *  - every pair removed by the rounding commits (COMMITS below), file by file;
 *  - every Point of a protected id in all past versions of the stories/history layers and ky-history.json.
 * Pairs that are still published anywhere in the current tree (public towns, markers) are dropped.
 * Only keyed hashes are stored. The key lives in env PROTECTED_COORDS_KEY (an Amplify secret, never in the
 * repo); without it the list cannot be brute-forced back to coordinates.
 * Needs full git history and the key; run by hand after adding a protected site:
 *   PROTECTED_COORDS_KEY=... node scripts/build-protected-coord-hashes.mjs
 */
import fs from 'node:fs'
import { execFileSync } from 'node:child_process'
import { extractPairs, buildHashFile } from './lib/coord-pairs.mjs'

const KEY = process.env.PROTECTED_COORDS_KEY
if (!KEY) { console.error('build-protected-coord-hashes: set PROTECTED_COORDS_KEY (same value as the Amplify secret)'); process.exit(1) }

const COMMITS = ['dce2127', '051f0e0', '7dfe914', 'b7070bd', ...(process.env.EXTRA_COMMITS || '').split(',').filter(Boolean)] // #221: rounding, leak fixes, source rounding; #226: Eskippakithiki; EXTRA_COMMITS: later rounding commits (e.g. Page Site)
const HISTORY_FILES = ['public/data/layers/stories.geojson', 'public/data/layers/history.geojson', 'public/data/app/ky-history.json', 'public/content/stories-locations.json']
const git = (...a) => execFileSync('git', a, { encoding: 'utf8', maxBuffer: 1 << 30, stdio: ['ignore', 'pipe', 'ignore'] })
const show = (rev, f) => { try { return git('show', `${rev}:${f}`) } catch { return '' } }

const ids = new Set(JSON.parse(fs.readFileSync('public/data/web/protected-pins.json', 'utf8')).ids)
const known = new Set()
const add = (set) => set.forEach((p) => known.add(p))

for (const c of COMMITS) {
  for (const f of git('diff', '--name-only', `${c}^`, c).split('\n').filter(Boolean)) {
    const before = extractPairs(show(`${c}^`, f)), after = extractPairs(show(c, f))
    add([...before].filter((p) => !after.has(p)))
  }
}
function protectedPoints(text) {
  const out = new Set()
  let d
  try { d = JSON.parse(text) } catch { return out }
  const visit = (o) => {
    if (Array.isArray(o)) return o.forEach(visit)
    if (!o || typeof o !== 'object') return
    const p = o.properties || o
    if ([p.id, p.historyId, p.slug].some((x) => ids.has(x))) {
      const g = o.geometry?.coordinates
      if (Array.isArray(g) && typeof g[0] === 'number') extractPairs(`${g[1]},${g[0]}`).forEach((x) => out.add(x))
      for (const [la, lo] of [['lat', 'lon'], ['latitude', 'longitude']]) if (typeof p[la] === 'number') extractPairs(`${p[la]},${p[lo]}`).forEach((x) => out.add(x))
    }
    Object.values(o).forEach((v) => v && typeof v === 'object' && visit(v))
  }
  visit(d)
  return out
}
for (const f of HISTORY_FILES) for (const rev of git('log', '--format=%H', '--', f).split('\n').filter(Boolean)) add(protectedPoints(show(rev, f)))

// Drop anything still published for a non-protected reason (shared town points etc.).
const current = new Set()
for (const f of git('ls-files', 'public/data', 'public/content', 'public/maps', 'src', 'scripts').split('\n')) {
  if (!/\.(json|geojson|js|mjs|md|gpx|kml)$/.test(f) || f.includes('protected-coords')) continue
  try { extractPairs(fs.readFileSync(f, 'utf8')).forEach((p) => current.add(p)) } catch { /* removed */ }
}
const dropped = [...known].filter((p) => current.has(p))
const kept = [...known].filter((p) => !current.has(p))
const out = buildHashFile(kept, KEY, 'Keyed HMAC-SHA256 (first 32 hex) of "lat,lon" for known exact coordinates of protected sites. Key: env PROTECTED_COORDS_KEY (Amplify secret, not in the repo); cannot be reversed without it. Generated by scripts/build-protected-coord-hashes.mjs; normalization in scripts/lib/coord-pairs.mjs.')
fs.writeFileSync('scripts/protected-coords.hashes.json', JSON.stringify(out, null, 1) + '\n')
console.log(`protected-coords hashes: ${out.count} (dropped ${dropped.length} pairs still published for public places)`)
